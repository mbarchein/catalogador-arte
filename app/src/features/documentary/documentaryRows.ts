// ── Shared ───────────────────────────────────────────────────

/**
 * es-ES comparison, accents in their place and case ignored, decided here and
 * not in the query: the database's own collation can sort «Óleo» past the z.
 */
function compareText(a: string, b: string): number {
  return a.localeCompare(b, 'es', { sensitivity: 'base' })
}
