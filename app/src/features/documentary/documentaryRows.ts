/**
 * What each documentary block asks the database for, and what it does with the
 * answer.
 *
 * One shape and one column list per area, written out as strings because a
 * TypeScript type does not exist at run time — the same reason `artworkImages.ts`
 * and `photoDetails.ts` keep theirs. Whatever an interface here declares, its
 * `*_COLUMNS` constant has to select: a field the query forgets arrives as
 * `undefined` with the type promising a value, which is the bug the corners of a
 * photograph already cost this project once.
 *
 * **Retired master rows are NOT filtered out.** The bridge rows are (`active`),
 * because a retired citation is in the trash and the record does not show it;
 * but the reference, the venue, the party or the document type behind an active
 * row is loaded whatever its state, for the reason `usePhysicalPlaces` gives:
 * hiding it would leave a blank where a name used to be, and that is the one
 * thing this application does not do. Whoever paints a retired name greys it
 * out; nobody removes it.
 *
 * The ORDER of four of the five blocks is decided here and not in the query, and
 * it is not a preference: PostgREST cannot order a parent by a column of an
 * embedded row, and the order of these lists is a column of the embedded row —
 * the year of the reference, the opening date of the show. Sorting in the client
 * also makes it pure, which is the only way it gets verified: the battery runs
 * in node.
 */

